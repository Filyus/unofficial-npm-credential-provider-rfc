def rust_string_array(values: list[str]) -> str:
    rendered = ["["]
    rendered.extend(f"    {json.dumps(value)}," for value in values)
    rendered.append("]")
    return "\n".join(rendered)


def markdown_values(values: list[str]) -> str:
    return ", ".join(f"`{value}`" for value in values)


def json_bool(value: bool) -> str:
    return "true" if value else "false"


def json_value(value: object) -> str:
    if isinstance(value, bool):
        return json_bool(value)
    return str(value)


